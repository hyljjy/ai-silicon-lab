import diag_netlist as dn  # noqa: E402

HEAD = "/* Generated by Yosys 0.69+187 (git sha1 2f08661dd, Release, Clang /usr/bin/clang++ 21.1.8) */\n\n"
MOD = ("module dot4sat(clk, rst);\n  input clk;\n  wire clk;\n  input [63:0] in_a;\n  wire [63:0] in_a;\n"
       "{decl}"
       "  assign e3[33:32] = { e3[31], e3[31] };\n  assign x = 1'b0;\n"
       "  sky130_fd_sc_hd__dfxtp_1 _12336_ (\n    .CLK(clk),\n    .D(_00033_),\n    .Q(v2)\n  );\n"
       "endmodule\n")


def net(decl="  wire signed [15:0] a0;\n  wire signed [15:0] a1;\n"):
    return HEAD + MOD.replace("{decl}", decl)


class TransformTest(unittest.TestCase):
    def test_removes_only_signed_from_declarations(self):
        t = dn.transform(net())
        self.assertTrue(t["ok"], t["reason"])
        self.assertEqual(t["text"], net("  wire [15:0] a0;\n  wire [15:0] a1;\n"))
        self.assertEqual(len(t["changed"]), 2)

    def test_reg_and_no_range_and_escaped_identifier(self):
        t = dn.transform(net("  reg signed q;\n  wire signed [3:0] \\u.x[1] ;\n"))
        self.assertTrue(t["ok"], t["reason"])
        self.assertIn("  reg q;\n", t["text"])
        self.assertIn("  wire [3:0] \\u.x[1] ;\n", t["text"])

    def test_crlf_kept(self):
        t = dn.transform(net().replace("\n", "\r\n"))
        self.assertTrue(t["ok"], t["reason"])
        self.assertIn("  wire [15:0] a0;\r\n", t["text"])

    def test_no_signed_is_a_no_op(self):
        t = dn.transform(net(""))
        self.assertTrue(t["ok"], t["reason"])
        self.assertEqual(t["text"], net(""))
        self.assertEqual(t["changed"], [])

    def test_stops(self):
        cases = {
            "port": "  input signed [3:0] p;\n",
            "assigned declaration": "  wire signed [3:0] a = b;\n",
            "system function": "  assign y = $signed(b);\n",
            "two names": "  wire signed [3:0] a, b;\n",
            "always": "  always @(posedge clk) q <= d;\n",
            "initial": "  initial q = 0;\n",
            "operator in assign": "  assign y = a & b;\n",
            "negation in assign": "  assign y = ~a;\n",
            "operator in connection": "  foo u (.A(~x));\n",
            "string": '  bar u (.S("x"));\n',
            "comment on decl": "  wire signed [3:0] a; // c\n",
        }
        for what, decl in cases.items():
            with self.subTest(what):
                self.assertFalse(dn.transform(net(decl))["ok"])

    def test_signed_inside_escaped_identifier_or_longer_name_is_not_signed(self):
        for decl in ("  wire \\signed_bus ;\n", "  wire unsigned_x;\n", "  wire signed_x;\n"):
            with self.subTest(decl):
                t = dn.transform(net(decl))
                self.assertTrue(t["ok"], t["reason"])
                self.assertEqual(t["changed"], [])

    def test_verify_transform_catches_other_changes(self):
        old = net()
        new = old.replace(".D(_00033_)", ".D(_00034_)")
        self.assertTrue(dn.verify_transform(old, new, []))
        t = dn.transform(old)
        self.assertEqual(dn.verify_transform(old, t["text"], t["changed"]), [])
        self.assertTrue(dn.verify_transform(old, t["text"], t["changed"][:1]))

    def test_instance_count(self):
        self.assertEqual(dn.instance_count(net()), 1)


class RewriteTest(unittest.TestCase):
    REC = "/mnt/d/r/runs/base"
    SRC = "/mnt/d/r/evidence/F1/archive/base"

    def test_three_substitutions_only(self):
        argv = ["iverilog", "-o", "gl_sim/sim.vvp", f"{self.REC}/inputs/tb/tb.v", f"{self.REC}/synth/netlist.v",
                "/home/eda/pdk/x.v", f"+VEC={self.REC}/vectors/vectors.txt", "+L=1"]
        out, ch = dn.rewrite(argv, self.REC, self.SRC, "/d/diag/netlist.v", "/d/diag/sta")
        self.assertEqual(out, ["iverilog", "-o", "gl_sim/sim.vvp", f"{self.SRC}/inputs/tb/tb.v", "/d/diag/netlist.v",
                               "/home/eda/pdk/x.v", f"+VEC={self.SRC}/vectors/vectors.txt", "+L=1"])
        self.assertEqual(len(ch), 3)

    def test_sta_dir_and_same_root(self):
        argv = ["/usr/bin/python3", "-B", f"{self.REC}/inputs/scripts/check_sta.py", f"{self.REC}/sta", "27.91"]
        out, ch = dn.rewrite(argv, self.REC, self.REC, "/d/n.v", "/d/diag/sta")
        self.assertEqual(out[3], "/d/diag/sta")
        self.assertEqual(out[2], argv[2])
        self.assertEqual(len(ch), 1)

    def test_check_argv(self):
        rec, net, sta = self.REC, "/d/diag/netlist.v", "/d/diag/sta"
        ok = dn.check_argv("gl_compile", ["iverilog", "tb.v", net], rec, self.SRC, self.SRC + "/synth/netlist.v",
                           net, sta)
        self.assertEqual(ok, [])
        self.assertTrue(dn.check_argv("gl_compile", ["iverilog", "tb.v", f"{rec}/synth/netlist.v"], rec, self.SRC,
                                      self.SRC + "/synth/netlist.v", net, sta))
        self.assertTrue(dn.check_argv("gl_sim", ["vvp", f"+VEC={rec}/vectors/v.txt"], rec, self.SRC,
                                      self.SRC + "/synth/netlist.v", net, sta))
        self.assertTrue(dn.check_argv("check_sta", ["py", f"{self.SRC}/sta"], rec, self.SRC,
                                      self.SRC + "/synth/netlist.v", net, sta))

    def test_recorded_root(self):
        steps = [{"step": "sta", "argv": ["sta", "-exit", f"{self.REC}/inputs/scripts/sta_run.tcl"]}]
        self.assertEqual(dn.recorded_root(steps), self.REC)


